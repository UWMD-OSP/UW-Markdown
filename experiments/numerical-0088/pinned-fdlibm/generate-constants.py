"""Freeze exact binary64 constants from pinned C decimal tokens; offline --check.

Every decimal rational rounds by exact adjacent binary64 midpoint comparison.
No Python float, Decimal precision, Node parser or host libm determines a word.
"""
import argparse
from fractions import Fraction
import hashlib
import importlib.util
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent
HELPER = ROOT.parent / "power-procedures" / "reference.py"
spec = importlib.util.spec_from_file_location("exact_word_reference_0088", HELPER)
P = importlib.util.module_from_spec(spec)
spec.loader.exec_module(P)
TOKEN = re.compile(r"(?<![A-Za-z0-9_.])(?:[0-9]+\.[0-9]*|\.[0-9]+)(?:[eE][+-]?[0-9]+)?|(?<![A-Za-z0-9_.])[0-9]+[eE][+-]?[0-9]+")


def decimal(token):
    pieces = re.split("[eE]", token)
    digits = pieces[0].replace(".", "")
    scale = (int(pieces[1]) if len(pieces) == 2 else 0) - (len(pieces[0].split(".")[1]) if "." in pieces[0] else 0)
    return Fraction(int(digits) * 10 ** scale) if scale >= 0 else Fraction(int(digits), 10 ** -scale)


def documents():
    manifest = json.loads((ROOT / "sources.json").read_bytes())
    literals = {}
    for item in manifest["files"]:
        raw = (ROOT / "upstream" / item["file"]).read_bytes()
        if len(raw) != item["bytes"] or hashlib.sha256(raw).hexdigest() != item["sha256"]:
            raise ValueError("Pinned source identity mismatch: " + item["file"])
        if item["file"].endswith(".h"):
            continue
        text = re.sub(r"/\*.*?\*/", "", raw.decode(), flags=re.S)
        for match in TOKEN.finditer(text):
            token = match[0]
            literals[token] = P.hexword(P.nearest(decimal(token)))
    # Small exact floating integers used by C's implicit int->double conversions.
    for token in ("0.0", "1.0", "2.0", "3.0", "0.5", "0.25"):
        literals[token] = P.hexword(P.nearest(decimal(token)))
    document = {"status": "UNACCEPTED exact RN-even constant-word derivation",
                "rounding_helper_sha256": hashlib.sha256(HELPER.read_bytes()).hexdigest(),
                "meaning": "nonnegative C floating token magnitude; unary minus remains an exact sign operation",
                "literals": dict(sorted(literals.items()))}
    encoded = (json.dumps(document, indent=2) + "\n").encode()
    module = "// Generated by generate-constants.py from exact rational decimal tokens.\nimport { fromBits } from './words.mjs';\nexport const C = Object.freeze({\n"
    module += "".join(f"  '{token}': fromBits('{bits}'),\n" for token, bits in sorted(literals.items()))
    module += "});\n"
    return {"constants.json": encoded, "constants.mjs": module.encode()}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(); parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, expected in documents().items():
        path = ROOT / name
        if args.check:
            if path.read_bytes() != expected:
                raise SystemExit("Constant/source mismatch: " + name)
        else:
            if path.exists():
                raise SystemExit("Refusing to overwrite frozen constants: " + name)
            path.write_bytes(expected)
    print("Exact constant words and eight source hashes match" if args.check else "Wrote first exact constant-word freeze")
