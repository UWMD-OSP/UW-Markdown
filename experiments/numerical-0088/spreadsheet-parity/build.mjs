import fs from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const out = path.resolve(process.argv[2] ?? 'spreadsheet-authored-output');
await fs.mkdir(out, {recursive:true});
const {Workbook, SpreadsheetFile} = await import(process.env.UWMD_ARTIFACT_TOOL ? pathToFileURL(process.env.UWMD_ARTIFACT_TOOL).href : '@oai/artifact-tool');
const wb = Workbook.create();
const sh = wb.worksheets.add('Numerical controls');
sh.showGridLines = false;
sh.getRange('A1:H1').values = [['RFC 0088 native spreadsheet controls',null,null,null,null,null,null,null]];
sh.getRange('A2:H2').values = [['Synthetic inputs; native Excel outcomes are observations, not the pinned contract.',null,null,null,null,null,null,null]];
sh.getRange('A3:H3').values = [['Control','Input x','Input y','Input z','Input w','Scope','Raw native result','Reported result']];
const controls = JSON.parse(await fs.readFile(new URL('./controls.json', import.meta.url), 'utf8')).controls;
sh.getRange('A4:F13').values = controls.map(r=>r.slice(0,6));
sh.getRange('G4:H13').formulas = controls.map(r=>r.slice(6));
sh.getRange('A1:H13').format.font = {name:'Arial',size:10};
sh.getRange('A3:H3').format = {fill:'#243746',font:{name:'Arial',size:10,bold:true,color:'#FFFFFF'}};
sh.getRange('A1').format.font = {name:'Arial',size:14,bold:true};
sh.getRange('B4:E13').setNumberFormat('0.################');
sh.getRange('G4:H13').setNumberFormat('0.############');
sh.getRange('A3:H13').format.autofitColumns();
sh.getRange('B3:E13').format.columnWidth = 14;
sh.getRange('F3:F13').format.columnWidth = 30;
sh.getRange('G3:H13').format.columnWidth = 24;
wb.recalculate();
await fs.writeFile(path.join(out,'artifact-inspect.ndjson'),(await wb.inspect({kind:'table',range:'Numerical controls!A3:H13',include:'values,formulas',tableMaxRows:11,tableMaxCols:8,maxChars:4000})).ndjson);
await fs.writeFile(path.join(out,'preview.png'),new Uint8Array(await (await wb.render({sheetName:'Numerical controls',range:'A1:H13',scale:1,format:'png'})).arrayBuffer()));
await (await SpreadsheetFile.exportXlsx(wb)).save(path.join(out,'controls.xlsx'));
await fs.writeFile(path.join(out,'controls.json'),JSON.stringify({scope:'UNACCEPTED scalar/ADS native Excel observation, not a pinned implementation',controls},null,2));
console.log('Exported one synthetic 10-control workbook.');
