// Regenerate packages/uwmd-core/src/metric-dictionary.ts from the normative
// metric dictionary, spec/metrics/builtin.json (RFC 0083 §1: the dictionary
// ships in the package as data). `metric-dictionary.test.ts` fails when the two
// differ, so run this after any change to builtin.json:
//
//   npm run gen-metric-dictionary
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dictionary = JSON.parse(readFileSync(join(root, 'spec/metrics/builtin.json'), 'utf8'));

const source = `// GENERATED by scripts/gen-metric-dictionary.mjs from spec/metrics/builtin.json.
// Do not edit: change the spec file and run \`npm run gen-metric-dictionary\`.
//
// The normative builtin metric dictionary (Protocol §XIII, spec/metrics/),
// shipped as package data so a verifier needs no file outside the package
// (RFC 0083 §1). \`metric-dictionary.test.ts\` asserts it deep-equals the spec.

import type { MetricDictionary } from './protocol.js';

function deepFreeze<T>(value: T): T {
  if (value && typeof value === 'object' && !Object.isFrozen(value)) {
    for (const member of Object.values(value)) deepFreeze(member);
    Object.freeze(value);
  }
  return value;
}

export const BUILTIN_METRIC_DICTIONARY: MetricDictionary = deepFreeze<MetricDictionary>(${JSON.stringify(dictionary, null, 2)});
`;

writeFileSync(join(root, 'packages/uwmd-core/src/metric-dictionary.ts'), source);
console.log('wrote packages/uwmd-core/src/metric-dictionary.ts');
